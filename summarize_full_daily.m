root = pwd;
T = table;
for j = 1:3
    if j == 1, strategy = 1; tag = 's1'; controller = "ES";
    elseif j == 2, strategy = 3; tag = 's3'; controller = "SA full";
    else, strategy = 3; tag = 'no_r'; controller = "SA no resistance"; end
    path = fullfile(root,['full_daily_' tag], ...
        sprintf('full_daily_%s.mat',tag));
    A = load(path,'R'); R = A.R;
    assert(R.nd == 365 && isfinite(R.eolYear));
    n = 365;
    row = table(controller,strategy,R.eolYear,numel(R.yr), ...
        min(R.SoH(n,:)),sum(R.Esrv(1:n)),sum(R.Eun(1:n)), ...
        sum(R.Ecurt(1:n)),sum(R.Eloss(1:n)),sum(R.Vol(1:n)), ...
        sum(R.Esrv(1:8*n)),sum(R.Eun(1:8*n)), ...
        sum(R.Eloss(1:8*n)),sum(R.Vol(1:8*n)), ...
        'VariableNames',{'controller','strategy','eolYears','simulatedDays', ...
        'year1MinSoH','year1ServedKWh','year1UnservedKWh', ...
        'year1CurtailedKWh','year1BatteryLossKWh','year1WaterM3', ...
        'eightYearServedKWh','eightYearUnservedKWh', ...
        'eightYearBatteryLossKWh','eightYearWaterM3'});
    T = [T;row]; %#ok<AGROW>
end
writetable(T,'full_daily_summary.csv');
disp(T);
